export function translateNavLabel(
  item: { name: string; href: string; section?: string },
  t: (key: string, fallback?: string) => string,
): { name: string; section?: string } {
  const key = NAV_HREF_I18N[item.href];
  const sectionKey = item.section ? SECTION_I18N[item.section] : undefined;
  return {
    name: key ? t(key, item.name) : item.name,
    section: sectionKey ? t(sectionKey, item.section) : item.section,
  };
}
